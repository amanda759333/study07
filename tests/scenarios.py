def csv_bytes(rows: list[str]) -> bytes:
    """엑셀이 저장한 것처럼 BOM과 CRLF를 붙인 CSV."""
    return ("\r\n".join([HEADER, *rows]) + "\r\n").encode("utf-8-sig")


def numbers(rows: list[str]) -> dict[str, str]:
    """이름 → 학번. 예: {'학생1': '2026101', …}"""
    return {r.split(",")[1]: r.split(",")[0] for r in rows}
